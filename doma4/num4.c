#include<stdio.h>
int main(void){
    int x = 0, y;
    printf("Чтобы завершить ввод, используй Ctrl+D\n");
    while (scanf("%d", &y) == 1){
        if (y%2!=0){
            x += 1;
        }   
    }
    printf("Количество нечетных: %d\n", x);
    return 0;
}
//вариант 6
// x*=y и x+=y равносильны x = x*y и x = x+y - используются для более краткой записи накопления суммы и произведения